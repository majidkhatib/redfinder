"""
Bundles sound_items.json, thresholds.json and sounds/ into web/data.js, so the web
version opens straight from disk (browsers block fetch() on file:// pages).

Run again after changing any of those files:  python web/build_data.py
"""
import base64
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

with open(os.path.join(ROOT, "sound_items.json"), encoding="utf8") as f:
    sounds = json.load(f)
with open(os.path.join(ROOT, "thresholds.json"), encoding="utf8") as f:
    thresholds = json.load(f)
audio = {}
for s in sounds:
    with open(os.path.join(ROOT, "sounds", s["file"]), "rb") as f:
        audio[s["file"]] = base64.b64encode(f.read()).decode("ascii")

data = {"sounds": sounds, "thresholds": thresholds, "audio": audio}
with open(os.path.join(HERE, "data.js"), "w", encoding="utf8") as f:
    f.write("// Generated by build_data.py from sound_items.json, thresholds.json and sounds/. Do not edit.\n")
    f.write("const REDFINDER_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"Wrote web/data.js ({len(sounds)} sounds)")
